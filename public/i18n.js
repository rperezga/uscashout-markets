    function t(key, esText) {
        if (lang === 'en' && EN[key]) return EN[key];
        return esText !== undefined ? esText : (EN[key] || key);
    }

    function applyStaticI18n() {
        document.documentElement.lang = lang;
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (el.dataset.i18nOrig === undefined) el.dataset.i18nOrig = el.innerHTML;
            el.innerHTML = (lang === 'en' && EN[key]) ? EN[key] : el.dataset.i18nOrig;
        });
        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            if (el.dataset.i18nTitleOrig === undefined) el.dataset.i18nTitleOrig = el.getAttribute('title') || '';
            el.setAttribute('title', (lang === 'en' && EN[key]) ? EN[key] : el.dataset.i18nTitleOrig);
        });
        const toggle = document.getElementById('lang-toggle-btn');
        if (toggle) toggle.textContent = lang === 'es' ? '🌐 EN' : '🌐 ES';
    }

    function setLang(newLang) {
        lang = newLang === 'en' ? 'en' : 'es';
        try { localStorage.setItem('xrpLang', lang); } catch (e) { /* no-op */ }
        applyStaticI18n();
        // app.js escucha este evento para re-renderizar los textos dinámicos
        window.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
    }

    window.t = t;
    window.getLang = getLang;
    window.setLang = setLang;
    window.applyStaticI18n = applyStaticI18n;

    document.addEventListener('DOMContentLoaded', () => {
        applyStaticI18n();
        const toggle = document.getElementById('lang-toggle-btn');
        if (toggle) toggle.addEventListener('click', () => setLang(lang === 'es' ? 'en' : 'es'));
    });
